using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Data;
using System.Drawing;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using System.Windows.Forms;
using DAL;
using BLL.Services;

namespace WinFormUI
{
    public partial class FrmAgentManagement : Form
    {
        private readonly AgentService _agentService;

        public FrmAgentManagement()
        {
            InitializeComponent();
            _agentService = new AgentService();
        }

        private void FrmAgentManagement_Load_1(object sender, EventArgs e)
        {
            LoadAgents();
        }

        private void LoadAgents()
        {
            try
            {
                var agents = _agentService.GetAllAgents();
                dgvAgents.DataSource = agents;

                // Hide navigation property (Orders) generated by Entity Framework 
                if (dgvAgents.Columns["Orders"] != null)
                {
                    dgvAgents.Columns["Orders"].Visible = false;
                }

                // Set column headers for better appearance and define width ratios
                if (dgvAgents.Columns["AgentID"] != null)
                {
                    dgvAgents.Columns["AgentID"].HeaderText = "ID";
                    dgvAgents.Columns["AgentID"].FillWeight = 12;
                }
                if (dgvAgents.Columns["AgentName"] != null)
                {
                    dgvAgents.Columns["AgentName"].HeaderText = "Agent Name";
                    dgvAgents.Columns["AgentName"].FillWeight = 33;
                }
                if (dgvAgents.Columns["Address"] != null)
                {
                    dgvAgents.Columns["Address"].HeaderText = "Address";
                    dgvAgents.Columns["Address"].FillWeight = 38;
                }
                if (dgvAgents.Columns["Phone"] != null)
                {
                    dgvAgents.Columns["Phone"].HeaderText = "Phone";
                    dgvAgents.Columns["Phone"].FillWeight = 17;
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Error loading agent list: " + ex.Message, "Error", 
                    MessageBoxButtons.OK, MessageBoxIcon.Error
                );
            }
        }

        private void dgvAgents_CellContentClick(object sender, DataGridViewCellEventArgs e)
        {
            if (e.RowIndex < 0) return;

            var row = dgvAgents.Rows[e.RowIndex];
            txtAgentId.Text = row.Cells["AgentID"].Value?.ToString();
            txtAgentName.Text = row.Cells["AgentName"].Value?.ToString();
            txtAddress.Text = row.Cells["Address"].Value?.ToString();
            txtPhone.Text = row.Cells["Phone"].Value?.ToString();
        }

        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                var newAgent = new Agent
                {
                    AgentName = txtAgentName.Text,
                    Address = txtAddress.Text,
                    Phone = txtPhone.Text
                };

                _agentService.AddAgent(newAgent);
                MessageBox.Show("Successfully added new agent!", "Notification", 
                    MessageBoxButtons.OK, MessageBoxIcon.Information);

                LoadAgents();
                ClearInputs();
            }
            catch (ArgumentException ex)
            {
                MessageBox.Show(ex.Message, "Invalid Data", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (InvalidOperationException ex)
            {
                MessageBox.Show(ex.Message, "Duplicate Data", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error adding agent: " + ex.Message, "System Error", 
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void btnUpdate_Click(object sender, EventArgs e)
        {
            if (string.IsNullOrWhiteSpace(txtAgentId.Text))
            {
                MessageBox.Show("Please select an agent from the table to update.", "No Selection", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            try
            {
                var updatedAgent = new Agent
                {
                    AgentID = int.Parse(txtAgentId.Text),
                    AgentName = txtAgentName.Text,
                    Address = txtAddress.Text,
                    Phone = txtPhone.Text
                };

                _agentService.UpdateAgent(updatedAgent);
                MessageBox.Show("Successfully updated agent information!", "Notification",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);

                LoadAgents();
                ClearInputs();
            }
            catch (ArgumentException ex)
            {
                MessageBox.Show(ex.Message, "Invalid Data", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (InvalidOperationException ex)
            {
                MessageBox.Show(ex.Message, "Duplicate Data", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error updating agent: " + ex.Message, "System Error", 
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void btnDelete_Click(object sender, EventArgs e)
        {
            if (string.IsNullOrWhiteSpace(txtAgentId.Text))
            {
                MessageBox.Show("Please select an agent from the table to delete.", "No Selection", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            var confirm = MessageBox.Show(
                $"Are you sure you want to delete the agent '{txtAgentName.Text}'?",
                "Confirm Delete",
                MessageBoxButtons.YesNo,
                MessageBoxIcon.Question
            );

            if (confirm != DialogResult.Yes) return;

            try
            {
                int agentId = int.Parse(txtAgentId.Text);
                _agentService.DeleteAgent(agentId);
                MessageBox.Show("Successfully deleted agent!", "Notification", 
                    MessageBoxButtons.OK, MessageBoxIcon.Information);

                LoadAgents();
                ClearInputs();
            }
            catch (InvalidOperationException ex)
            {
                MessageBox.Show(ex.Message, "Cannot Delete", 
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (Exception ex)
            {
                MessageBox.Show("Error deleting agent: " + ex.Message, "System Error", 
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void btnClear_Click(object sender, EventArgs e)
        {
            ClearInputs();
        }

        private void ClearInputs()
        {
            txtAgentId.Clear();
            txtAgentName.Clear();
            txtAddress.Clear();
            txtPhone.Clear();
            dgvAgents.ClearSelection();
            txtAgentName.Focus();
        }

        private void txtAgentId_TextChanged(object sender, EventArgs e)
        {

        }
    }
}
